// Turns source videos into the clips the Page plays, and writes the manifest.
//
//   node scripts/prepare-videos.js 1=videos/first.mp4 2=videos/second.mp4 [3=...]
//   node scripts/prepare-videos.js --placeholder 2 [--seconds 8]   synthetic test clips (no real content)
//
// Output: agent/assets/videos/relax-N.mp4 and agent/lib/videos.js.
//
// Every clip is re-encoded for the glasses: no audio track at all (the app is silent
// by design), H.264 Main profile in a progressive MP4 with the index at the front
// (the only format AIUI's <video> plays), at most 480 x 352, 30 fps at most.
// Needs ffmpeg and ffprobe on PATH (or FFMPEG / FFPROBE set).

import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'agent', 'assets', 'videos');
const MANIFEST = join(ROOT, 'agent', 'lib', 'videos.js');
const FFMPEG = process.env.FFMPEG || 'ffmpeg';
const FFPROBE = process.env.FFPROBE || 'ffprobe';

export const MAX_VIDEOS = 4;
export const MAX_WIDTH = 480;
export const MAX_HEIGHT = 352;

function run(command, args) {
  const result = spawnSync(command, args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  if (result.error) throw new Error(command + ' could not run: ' + result.error.message);
  if (result.status !== 0) throw new Error(command + ' failed:\n' + String(result.stderr).split('\n').slice(-12).join('\n'));
  return result.stdout;
}

export function probe(file) {
  const json = JSON.parse(run(FFPROBE, [
    '-v', 'error',
    '-show_entries', 'stream=codec_type,codec_name,profile,pix_fmt,width,height,r_frame_rate:format=duration',
    '-of', 'json', file
  ]));
  const streams = json.streams || [];
  const video = streams.find((s) => s.codec_type === 'video');
  if (!video) throw new Error(file + ' has no video stream');
  const [num, den] = String(video.r_frame_rate || '0/1').split('/').map(Number);
  return {
    codec: video.codec_name,
    profile: video.profile,
    pixFmt: video.pix_fmt,
    width: video.width,
    height: video.height,
    fps: den ? num / den : 0,
    audioStreams: streams.filter((s) => s.codec_type === 'audio').length,
    durationSec: Number(json.format.duration)
  };
}

function encode(inputArgs, output, sourceFps) {
  const filters = ['scale=' + MAX_WIDTH + ':' + MAX_HEIGHT + ':force_original_aspect_ratio=decrease:force_divisible_by=2'];
  if (sourceFps > 30.5) filters.push('fps=30');
  run(FFMPEG, [
    '-y', '-v', 'error',
    ...inputArgs,
    '-an', '-sn', '-dn', '-map_metadata', '-1',
    '-vf', filters.join(','),
    '-c:v', 'libx264', '-profile:v', 'main', '-level', '4.0', '-pix_fmt', 'yuv420p',
    '-crf', '28', '-preset', 'slow',
    '-movflags', '+faststart',
    output
  ]);
}

function writeManifest(entries) {
  const lines = entries.map((e) => '  ' + JSON.stringify(e));
  const text = [
    '// Generated by scripts/prepare-videos.js. Do not edit by hand.',
    '// Each clip is silent (no audio track), H.264 in a progressive MP4.',
    '',
    'export const VIDEOS = [',
    lines.join(',\n'),
    '];',
    ''
  ].join('\n');
  writeFileSync(MANIFEST, text);
}

function entryFor(n, file, placeholder) {
  const info = probe(file);
  if (info.audioStreams !== 0) throw new Error(file + ' still has an audio track');
  return {
    id: 'relax-' + n,
    title: 'Relax ' + n,
    src: '/assets/videos/relax-' + n + '.mp4',
    durationSec: Math.round(info.durationSec * 10) / 10,
    bytes: statSync(file).size,
    width: info.width,
    height: info.height,
    placeholder
  };
}

function main(args) {
  mkdirSync(OUT_DIR, { recursive: true });
  const entries = [];
  if (args[0] === '--placeholder') {
    const count = Math.max(1, Math.min(MAX_VIDEOS, Number(args[1] || 2)));
    const secondsIndex = args.indexOf('--seconds');
    const seconds = secondsIndex === -1 ? 8 : Math.max(2, Math.min(600, Number(args[secondsIndex + 1]) || 8));
    const sources = ['testsrc2', 'rgbtestsrc', 'smptebars', 'testsrc'].map((name) => name + '=size=480x270:rate=24:duration=' + seconds);
    for (let n = 1; n <= count; n += 1) {
      const out = join(OUT_DIR, 'relax-' + n + '.mp4');
      encode(['-f', 'lavfi', '-i', sources[n - 1]], out, 24);
      entries.push(entryFor(n, out, true));
    }
  } else {
    if (args.length === 0) throw new Error('usage: node scripts/prepare-videos.js 1=path.mp4 2=path.mp4 [3=...]  |  --placeholder N');
    args.forEach((arg) => {
      const match = arg.match(/^(\d)=(.+)$/);
      if (!match || Number(match[1]) < 1 || Number(match[1]) > MAX_VIDEOS) throw new Error('bad argument: ' + arg);
      const n = Number(match[1]);
      const source = match[2];
      const info = probe(source);
      const out = join(OUT_DIR, 'relax-' + n + '.mp4');
      encode(['-i', source], out, info.fps);
      entries.push(entryFor(n, out, false));
    });
    entries.sort((a, b) => a.id.localeCompare(b.id));
  }
  writeManifest(entries);
  entries.forEach((e) => console.log(e.id + ': ' + e.durationSec + ' s, ' + (e.bytes / 1024).toFixed(0) + ' KB, ' + e.width + 'x' + e.height + (e.placeholder ? ' (placeholder)' : '')));
}

const invokedDirectly = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (invokedDirectly) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
